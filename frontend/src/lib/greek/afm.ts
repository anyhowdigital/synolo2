/**
 * Έλεγχος εγκυρότητας ΑΦΜ (9 ψηφία, αλγόριθμος modulo 11).
 */
export function isValidAfm(input: string): boolean {
  const afm = input.replace(/\s/g, "");
  if (!/^\d{9}$/.test(afm)) return false;
  if (afm === "000000000") return false;

  let sum = 0;
  for (let i = 0; i < 8; i++) {
    sum += parseInt(afm[i], 10) * Math.pow(2, 8 - i);
  }
  const check = (sum % 11) % 10;
  return check === parseInt(afm[8], 10);
}

export function normalizeAfm(input: string): string {
  const digits = input.replace(/\D/g, "");
  // Παλαιά 8ψήφια ΑΦΜ (εξαγωγές από άλλα προγράμματα) συμπληρώνονται με μηδενικό μπροστά.
  if (digits.length === 8 && isValidAfm(`0${digits}`)) return `0${digits}`;
  return digits.slice(0, 9);
}

